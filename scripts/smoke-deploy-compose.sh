# The `Accept` Chromium sends for an image; Firefox and Safari list image/avif
# too.
answer="$(curl -sS -o "${work}/label.avif" -w '%{http_code} %{content_type}' \
  -H 'Accept: image/avif,image/webp,image/apng,image/svg+xml,image/*,*/*;q=0.8' \
