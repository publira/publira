#!/usr/bin/env bash
# smoke-deploy-compose.sh — Bring infra/deploy/compose.yaml up from the images
# `task docker:verify:full` built, out of the archive a release publishes it in
# and extracted away from the checkout, take it through the steps its README
# documents, from generating .env to running `setup` a second time, and check
# that the tenant site, the tenant console, and the Platform Console answer
# through the edge, that `server` hosts the worker, that the proxy cannot reach
# the database or Valkey, and that image delivery converts an image to WebP and
# to AVIF and resizes it through libvips.
#
# The stack runs under its own project name, so an install on the same host is
# left alone, and is always removed with its volumes.
#
# Inputs (env):
#   PUBLIRA_DEPLOY_SMOKE_EDGE_PORT        Port the edge publishes plain HTTP on (default: 18090)
#   PUBLIRA_DEPLOY_SMOKE_EDGE_HTTPS_PORT  Port the edge publishes HTTPS on (default: 18443)
#   PUBLIRA_DEPLOY_SMOKE_TIMEOUT          Seconds to wait for each page (default: 120)
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
cd "${repo_root}"

edge_port="${PUBLIRA_DEPLOY_SMOKE_EDGE_PORT:-18090}"
edge_https_port="${PUBLIRA_DEPLOY_SMOKE_EDGE_HTTPS_PORT:-18443}"
timeout="${PUBLIRA_DEPLOY_SMOKE_TIMEOUT:-120}"
# The tenant is stored with the edge port it is reached on; the mail addresses
# take the host name alone.
domain=comics.localhost

# The Dev Container exports PUBLIRA_* for `task dev`, and Compose would let
# them override the env file.
for name in $(compgen -e); do
  case "${name}" in
    PUBLIRA_* | COMPOSE_*) unset "${name}" ;;
  esac
done

work="$(mktemp -d)"
version="$(jq -r .version package.json)"
install_dir="${work}/publira-deploy-${version}"
project=publira-deploy-smoke
# The .env beside compose.yaml is read the way it is on an operator's host.
compose() {
  docker compose -p "${project}" -f "${install_dir}/compose.yaml" "$@"
}
cleanup() {
  status=$?
  if [ "${status}" -ne 0 ]; then
    compose ps --all >&2 || true
    compose logs --no-color --tail 50 >&2 || true
  fi
  compose --profile '*' down -v --remove-orphans > /dev/null 2>&1 || true
  rm -rf "${work}"
  exit "${status}"
}
trap cleanup EXIT

echo "[deploy-smoke] extracting publira-deploy-${version}.tar.gz"
tar -C "${work}" -xzf "$(bash scripts/package-deploy.sh "${version}" "${work}")"

# The .env, written the way README.md tells the operator to: generated by the
# publiractl image, then the values an operator chooses set in it.
echo "[deploy-smoke] generating .env"
docker run --rm --user "$(id -u):$(id -g)" -v "${install_dir}:/work" -w /work publira/publiractl:local env generate > /dev/null
set_env() {
  local name="$1" value="$2"
  grep -q "^${name}=" "${install_dir}/.env" || {
    echo "[deploy-smoke] ERROR: the generated .env does not list ${name}" >&2
    return 1
  }
  sed -i "s|^${name}=.*|${name}=${value}|" "${install_dir}/.env"
}
set_env PUBLIRA_IMAGE_REGISTRY publira
set_env PUBLIRA_IMAGE_TAG local
# PUBLIRA_EDGE_ACME_EMAIL stays empty, as the trial on one machine leaves it:
# no certificate authority reaches a .localhost name, so the edge serves plain
# HTTP and nothing listens behind the HTTPS port.
set_env PUBLIRA_EDGE_HTTP_PORT "${edge_port}"
set_env PUBLIRA_EDGE_HTTPS_PORT "${edge_https_port}"
set_env PUBLIRA_EDGE_SITE_HOSTS "${domain}"
set_env PUBLIRA_EDGE_ADMIN_HOSTS "admin.${domain}"
set_env PUBLIRA_EDGE_PLATFORM_HOSTS platform.localhost
set_env PUBLIRA_TENANT_URL_SCHEME http
set_env COMPOSE_PROFILES web-platform,email-renderer
set_env PUBLIRA_WEB_PLATFORM_INTERNAL_URL http://web-platform:4100
set_env PUBLIRA_PLATFORM_APP_URL "http://platform.localhost:${edge_port}"
set_env PUBLIRA_EMAIL_RENDERER_URL http://email-renderer:8080

# `setup` migrates, creates the roles and the bucket, and saves the rest, which
# the operator answers on the terminal and the smoke gives as flags.
run_setup() {
  printf 'smoke' | compose run --rm -T setup --non-interactive \
    --default-locale en \
    --host smtp.invalid --port 587 --encryption starttls --username smoke --smtp-password-stdin --from-address "no-reply@${domain}" \
    --tenant-name "Smoke Comics" --domain "${domain}:${edge_port}" \
    --admin-email "owner@${domain}" --admin-name Owner --generate-admin-password
}
echo "[deploy-smoke] setting the install up"
run_setup > /dev/null

# Run again on the finished install, it migrates nothing and saves nothing; the
# roles only have the passwords they already hold set again.
run_setup > "${work}/setup-again"
if changed="$(grep -E '\s(created|updated)\s' "${work}/setup-again" | grep -v '^Database roles')"; then
  echo "[deploy-smoke] ERROR: setup run again changed the install:" >&2
  echo "${changed}" >&2
  exit 1
fi
echo "[deploy-smoke] ok: setup run again changes nothing"

echo "[deploy-smoke] starting the stack"
compose up -d

# Waits until the edge answers the host with a 200, following redirects, and
# with the text given when there is one; prints what it answered last otherwise.
expect_page() {
  local name="$1" host="$2" text="${3:-}"
  local deadline=$((SECONDS + timeout)) code=""
  while [ "${SECONDS}" -lt "${deadline}" ]; do
    code="$(curl -sS -o "${work}/page" -w '%{http_code}' -L \
      --resolve "${host}:${edge_port}:127.0.0.1" "http://${host}:${edge_port}/" || true)"
    if [ "${code}" = 200 ] && { [ -z "${text}" ] || grep -qF "${text}" "${work}/page"; }; then
      echo "[deploy-smoke] ok: ${name} (${host})"
      return 0
    fi
    sleep 2
  done
  echo "[deploy-smoke] ERROR: ${name} (${host}) answered ${code:-nothing}${text:+ without \"${text}\"}" >&2
  return 1
}

expect_page "tenant site" "${domain}" "Smoke Comics"
expect_page "tenant console" "admin.${domain}"
expect_page "Platform Console" "platform.localhost"

# A long-lived process that exited or keeps restarting is a failure even when
# every page above answered.
for service in server web-storefront web-admin web-platform email-renderer proxy; do
  state="$(compose ps --all --format '{{.State}}' "${service}")"
  restarts="$(docker inspect --format '{{.RestartCount}}' "$(compose ps --all -q "${service}")")"
  if [ "${state}" != running ] || [ "${restarts}" != 0 ]; then
    echo "[deploy-smoke] ERROR: ${service} is ${state} after ${restarts} restarts" >&2
    exit 1
  fi
done
echo "[deploy-smoke] ok: every long-lived process is running"

# `server` runs with the worker hosted in it, so it is the one container of the
# publira image, and it answers the readiness of both: the server's pools on
# :8000 and the worker's on :8003. The proxy, on the `edge` network with it,
# asks.
publira_services="$(compose ps --format '{{.Service}} {{.Image}}' | awk '$2 ~ /\/publira:/ { print $1 }')"
if [ "${publira_services}" != server ]; then
  echo "[deploy-smoke] ERROR: the publira image runs as $(paste -sd, - <<< "${publira_services:-nothing}"), want server alone" >&2
  exit 1
fi
expect_ready() {
  local port="$1" body check
  shift
  body="$(compose exec -T proxy wget -q -O - -T 5 "http://server:${port}/readyz" 2> /dev/null || true)"
  for check in "$@"; do
    if ! grep -qF "\"${check}\":{\"status\":\"ok\"}" <<< "${body}"; then
      echo "[deploy-smoke] ERROR: server:${port}/readyz answered ${body:-nothing}, want ${check} ok" >&2
      return 1
    fi
  done
}
expect_ready 8000 db.public db.admin db.platform
expect_ready 8003 db.outbox db.ticker db.content_stats

# The Outbox drain runs in `server`: an `outbox_test` entry, which its handler
# completes without a side effect, is done once the drain has claimed it.
event_id="$(compose exec -T postgres psql -U postgres -d publira -v ON_ERROR_STOP=1 -qtA -c "
  INSERT INTO outbox_events (id, event_type, idempotency_key)
  VALUES (gen_random_uuid(), 'outbox_test', 'deploy-smoke')
  RETURNING id")"
deadline=$((SECONDS + timeout))
event_status=""
while [ "${SECONDS}" -lt "${deadline}" ]; do
  event_status="$(compose exec -T postgres psql -U postgres -d publira -qtA -c "SELECT status FROM outbox_events WHERE id = '${event_id}'")"
  [ "${event_status}" = "done" ] && break
  sleep 2
done
if [ "${event_status}" != "done" ]; then
  echo "[deploy-smoke] ERROR: the outbox_test entry is ${event_status:-missing}, want done" >&2
  exit 1
fi
echo "[deploy-smoke] ok: server answers the readiness of both processes and drains the Outbox"

# The proxy reaches `server` and every web app, and is on the `edge` network
# alone, which holds neither the database nor Valkey.
from_proxy() { compose exec -T proxy wget -q -O /dev/null -T 5 "$1" 2> /dev/null; }
for url in http://server:8000/livez http://web-storefront:3000/livez http://web-admin:4000/livez http://web-platform:4100/livez; do
  if ! from_proxy "${url}"; then
    echo "[deploy-smoke] ERROR: the proxy cannot reach ${url}" >&2
    exit 1
  fi
done
proxy_networks="$(docker inspect --format '{{range $name, $_ := .NetworkSettings.Networks}}{{$name}} {{end}}' "$(compose ps -q proxy)")"
if [ "${proxy_networks}" != "${project}_edge " ]; then
  echo "[deploy-smoke] ERROR: the proxy is on ${proxy_networks}, want ${project}_edge alone" >&2
  exit 1
fi
echo "[deploy-smoke] ok: the proxy reaches server and the web apps, and not the database or Valkey"

# Image delivery converts and resizes through libvips, which the server binary
# links with CGO, so a server image whose runtime libvips does not match the
# one it was built against fails here and nowhere above, and so does one
# whose libheif has no AVIF encoder. Manael answers with the original bytes
# when a conversion fails, so the check is on the output: a WebP, and an AVIF
# for an `Accept` that prefers it, at the requested width. Manael converts only
# a JPEG to AVIF, so that check asks for one. The request is the one the apps'
# next/image loader makes, `fit=scale-down` included.
#
# A 64×32 PNG, stored the way a tenant's logo upload stores one.
printf '%s' 'iVBORw0KGgoAAAANSUhEUgAAAEAAAAAgCAIAAAAt/+nTAAAAN0lEQVR42u3PQQkAAAgEsItjCPtjLDP4FAYrsEzXaxEQEBAQEBAQEBAQEBAQEBAQEBAQEBAQuFq5D2CIoSw0JwAAAABJRU5ErkJggg==' |
  base64 -d > "${work}/logo.png"
# shellcheck disable=SC2016 # expanded inside the container
compose exec -T rustfs sh -c \
  'curl -fsS -X PUT --aws-sigv4 aws:amz:us-east-1:s3 --user "$RUSTFS_ACCESS_KEY:$RUSTFS_SECRET_KEY" -H "Content-Type: image/png" --data-binary @- http://localhost:9000/publira/smoke/logo.png' \
  < "${work}/logo.png" > /dev/null
image_id="$(compose exec -T postgres psql -U postgres -d publira -v ON_ERROR_STOP=1 -qtA -c "
  WITH image AS (
    INSERT INTO tenant_images (id, tenant_id) SELECT gen_random_uuid(), id FROM tenants RETURNING id, tenant_id
  )
  INSERT INTO tenant_image_variants
    (id, tenant_id, tenant_image_id, label, variant_type, storage_provider, object_key, content_type, file_size_bytes, width, height)
  SELECT gen_random_uuid(), tenant_id, id, 'logo-1x', 'logo', 's3', 'smoke/logo.png', 'image/png', $(wc -c < "${work}/logo.png"), 64, 32
  FROM image
