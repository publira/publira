/**
 * Where the tenant's storefront loads its Google tag from. The stored
 * `tenant_analytics_settings.serving_mode` values rather than the generated
 * enum, so the form, the `FormData` it submits, and the catalog keys naming
 * each option are all the same three strings.
 *
 * Kept apart from `tenant-analytics-settings.ts` because the form's mode picker
 * is a Client Component: importing the value from the module that reads the
 * session would pull `next/headers` into the browser graph.
 */
export type GoogleTagServingMode = "gateway" | "google" | "server_container";

/** The order the form offers: Google's own servers first, then the two first-party ways. */
export const GOOGLE_TAG_SERVING_MODES = [
  "google",
  "server_container",
  "gateway",
] as const satisfies readonly GoogleTagServingMode[];

export const isGoogleTagServingMode = (
  value: string
): value is GoogleTagServingMode =>
  GOOGLE_TAG_SERVING_MODES.some((mode) => mode === value);

/**
 * Whether the storefront asks a reader before the Google tag runs. The stored
 * `tenant_analytics_settings.consent_mode` values, for the same reason as
 * {@link GoogleTagServingMode}.
 */
export type GoogleTagConsentMode = "external" | "not_required" | "opt_in";

/** The order the form offers: no question first, then the storefront's banner, then the tenant's own tool. */
export const GOOGLE_TAG_CONSENT_MODES = [
  "not_required",
  "opt_in",
  "external",
] as const satisfies readonly GoogleTagConsentMode[];

export const isGoogleTagConsentMode = (
  value: string
): value is GoogleTagConsentMode =>
  GOOGLE_TAG_CONSENT_MODES.some((mode) => mode === value);

/** The Google tag the tenant's storefront loads. An empty string is a value not set. */
export interface TenantAnalyticsSettings {
  ga4MeasurementId: string;
  gtmContainerId: string;
  servingMode: GoogleTagServingMode;
  serverContainerUrl: string;
  /** Generated by the API on the first save in gateway mode; empty until then. */
  gatewayPath: string;
  consentMode: GoogleTagConsentMode;
}

/**
 * The tag the gateway path forwards to Google for, which is the one the tenant
 * registers the path against: the Tag Manager container where one is set, and
 * the GA4 measurement ID otherwise. Empty when neither is set.
 */
export const gatewayTagId = (
  settings: Pick<TenantAnalyticsSettings, "ga4MeasurementId" | "gtmContainerId">
): string => settings.gtmContainerId || settings.ga4MeasurementId;
