-- INDEX: idx_purchases_tenant_purchased_at_id
-- A tenant's purchases newest first, with the id breaking a tie between two
-- made at the same instant: the order the console lists them in, so that a
-- page token names one row and the next page starts right after it. The
-- daily content stats cut one UTC day out of the same order and group it by
-- episode, which the included episode_id answers from the index alone, so this
-- takes over from idx_purchases_tenant_purchased_at_episode, which the next
-- migration drops.
--
-- CONCURRENTLY, so building it does not block the purchases a storefront keeps
-- writing, which is also why this statement is the whole file.
CREATE INDEX CONCURRENTLY idx_purchases_tenant_purchased_at_id ON purchases USING btree (tenant_id, purchased_at DESC, id DESC) INCLUDE (episode_id);
