-- The Google tag a tenant's storefront loads, and where it is loaded from.
-- The IDs and the URLs appear in every page's HTML, so nothing here is secret.

-- TABLE: tenant_analytics_settings
-- A tenant without a row, and one whose row names neither ID, loads no tag.
-- The server validates and normalizes every value before storing it; the
-- checks only keep out a value the storefront could not build a tag from.
CREATE TABLE tenant_analytics_settings (
    tenant_id uuid NOT NULL,
    ga4_measurement_id text,
    gtm_container_id text,
    -- google loads the tag from Google; server_container loads it from, and
    -- sends hits to, server_container_url; gateway proxies gateway_path on the
    -- storefront origin.
    serving_mode text DEFAULT 'google'::text NOT NULL,
    -- An https origin with no path. Required by server_container, and the
    -- gateway's upstream in place of Google when it is set in gateway mode.
    server_container_url text,
    -- The path segment the gateway answers on, generated by the server. It
    -- holds an underscore, which no page slug may, so it cannot shadow one.
    gateway_path text,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT tenant_analytics_settings_ga4_measurement_id_check CHECK (ga4_measurement_id ~ '^G-[A-Z0-9]{1,30}$'),
    CONSTRAINT tenant_analytics_settings_gtm_container_id_check CHECK (gtm_container_id ~ '^GTM-[A-Z0-9]{1,28}$'),
    CONSTRAINT tenant_analytics_settings_serving_mode_check CHECK (serving_mode IN ('google', 'server_container', 'gateway')),
    CONSTRAINT tenant_analytics_settings_server_container_url_check CHECK (server_container_url ~ '^https://[a-z0-9.-]+(:[0-9]{1,5})?$'),
    CONSTRAINT tenant_analytics_settings_gateway_path_check CHECK (gateway_path ~ '^_[a-z2-7]{16}$'),
    CONSTRAINT tenant_analytics_settings_server_container_required_check CHECK (serving_mode <> 'server_container' OR server_container_url IS NOT NULL),
    CONSTRAINT tenant_analytics_settings_gateway_path_required_check CHECK (serving_mode <> 'gateway' OR gateway_path IS NOT NULL)
);

-- CONSTRAINT: tenant_analytics_settings tenant_analytics_settings_pkey
ALTER TABLE ONLY tenant_analytics_settings
    ADD CONSTRAINT tenant_analytics_settings_pkey PRIMARY KEY (tenant_id);

-- FK CONSTRAINT: tenant_analytics_settings tenant_analytics_settings_tenant_id_fkey
ALTER TABLE ONLY tenant_analytics_settings
    ADD CONSTRAINT tenant_analytics_settings_tenant_id_fkey FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE;

-- ROW SECURITY: tenant_analytics_settings
ALTER TABLE tenant_analytics_settings ENABLE ROW LEVEL SECURITY;

-- POLICY: tenant_analytics_settings tenant_analytics_settings_tenant_isolation
CREATE POLICY tenant_analytics_settings_tenant_isolation ON tenant_analytics_settings USING ((tenant_id = (NULLIF(current_setting('app.current_tenant_id'::text, true), ''::text))::uuid)) WITH CHECK ((tenant_id = (NULLIF(current_setting('app.current_tenant_id'::text, true), ''::text))::uuid));
